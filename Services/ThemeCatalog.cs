    public static int IndexOfId(string? id)
    {
        if (string.IsNullOrWhiteSpace(id))
            return -1;

        for (int i = 0; i < All.Count; i++)
        {
            if (string.Equals(All[i].Id, id, StringComparison.OrdinalIgnoreCase))
                return i;
        }

        return -1;
    }
